struct font
{
	int w, h;
	unsigned char *data;
};

int gprintf(struct fb *dst, struct font *font, int x0, int y0, int cl, char *format, ...)
{
	int i, x, y, n;
	char *msg;
	pixel *p = dst->pixbuf;
	va_list args;

	va_start(args, format);
	n = vsnprintf(NULL, 0, format, args);
	va_end(args);
	if (n < 0) return -1;

	msg = malloc(n + 1);
	if (!msg) return -1;

	va_start(args, format);
	n = vsnprintf(msg, n + 1, format, args);
	va_end(args);
	if (n < 0) { free(msg); return -1; }

	p += y0*dst->pitch + x0;
	for (y = 0; y < font->h; y++) {
		for (i = 0; msg[i]; i++) {
			for (x = 0; x < font->w; x++) {
				if ((font->data[((unsigned char)msg[i])*font->h + y] >> (7 - x)) & 1) p[x] = cl;
			}
			p += font->w;
		}
		p += (dst->pitch - font->w*n);
	}
	free(msg);
	return n;
}

