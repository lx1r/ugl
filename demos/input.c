int main()
{
	int ev, code = 0, data = 0;
	int msx = 64, msy = 64;
	struct fb *fb = fbopen(0, 0);
	struct fb *vfb = vfballoc(fb->w, fb->h);

	for (;;) {
		while ((ev = fbread(fb))) {
			code = evcode(ev);
			data = evdata(ev);
			if (code == MICE_DX) {
				msx += data;
				msx = clamp(msx, 0, vfb->w - 1);
			}
			if (code == MICE_DY) {
				msy += data;
				msy = clamp(msy, 0, vfb->h - 1);
			}
		}
		if (code == KEY_ESC) break;
		cls(vfb);
		gprintf(vfb, fxfnt, 4, 0, 0xffffff, "fps: %d", fps());
		gprintf(vfb, fxfnt, 4, 16, 0xffffff, "resolution: %dx%d", vfb->w, vfb->h);
		gprintf(vfb, fxfnt, 4, 32, 0xffffff, "scancode: %d, data: %d", code, data);
		gprintf(vfb, fxfnt, 4, 48, 0xffffff, "mouse: x=%d, y=%d", msx, msy);
		blit(vfb, msx, msy, msptr, pand);
		blit(vfb, msx, msy, msmsk, por);
		blit(fb, 0, 0, vfb, pmov);
	}
	fbclose(fb);
	return 0;
}

#include <time.h>

int fps()
{
	static time_t start = 0;
	static int frames = 0;
	static int fps = 0;

	time_t t = time(NULL);
	if (t > start) {
		fps = frames/(t - start);
		start = t;
		frames = 0;
	}
	frames++;

	return fps;
}

